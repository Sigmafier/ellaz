/* The words on the four printable pages. Hebrew only, written natively.
   ===========================================================================

   WHY HEBREW ONLY, AND WHY THAT IS A DECISION RATHER THAN A GAP. A printable
   worksheet is the one thing on this site somebody links to without playing
   anything, and the search that finds it is typed in Hebrew: "דפי עבודה
   להדפסה". An English arm would be four more documents competing in a language
   where this pack has no story to tell yet. `a-locale-page-without-a-translated
   -body-is-a-duplicate.md` is the other half of the same rule: a language gets
   a page when somebody writes the page, never because the route table could
   emit one. So these routes declare `locales: ["he"]` and their hreflang
   cluster is one entry - themselves.

   WHAT AN AUTHOR MAY WRITE HERE. Prose. Never a fact about a board and never a
   number they did not derive: every `{placeholder}` below is filled in by
   `printPage.ts` from `sheets.ts`, so the page cannot claim a grid size, a
   sheet count or a word count that the printed sheets do not have. Same split
   as `.claude/rules/game-content-template.md` describes for the game pages.

   NO EM DASH ANYWHERE IN THIS FILE. It is customer-facing copy. */

export interface PrintFaq {
  q: string;
  a: string;
}

export interface PrintSection {
  title: string;
  body: string[];
}

export interface PrintPageCopy {
  /** `<title>`, under the gate's 70-character ceiling. */
  metaTitle: string;
  /** The search snippet, under 160 characters. */
  metaDescription: string;
  h1: string;
  lede: string;
  /** The label on the link back to the game itself. */
  playLabel: string;
  /** What the sheets are, above them. */
  sheetsTitle: string;
  /**
   * The one line of instruction PRINTED ON EVERY SHEET.
   *
   * It is on the paper rather than in the prose because the prose is hidden
   * when the page prints. A sheet that reaches a classroom with no instruction
   * on it is a sheet somebody has to explain out loud.
   */
  sheetNote: string;
  /** The heading over the answer key, or empty when a pack has no answers. */
  answersTitle: string;
  /** One line under the answer heading, or empty. */
  answersNote: string;
  sections: PrintSection[];
  faq: PrintFaq[];
}

